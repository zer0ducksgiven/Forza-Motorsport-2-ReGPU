"""Builds src/gpu/shader_seed.h: compiled shaders the game makes at run time, which the first boot's scan
of the game files can't find and nearly every player then compiles during play (up to 28 s each).

  shader_seed.py <game log> <shader cache folder> [--variants] [--partial] [--out src/gpu/shader_seed.h]

The log is a run with FM2_SHADER_KEYS=1 that drew them ("shader key: vs <hash> <cache key>"). The bytecode is
<cache key>.dxbc in the cache.

--variants also adds every pixel shader variant in the log ("shader key: psk <hash> <cache key>", no alpha test;
"psf <hash> <mask> <cache key>", plain fetch), so a fresh install's boot doesn't run fxc for them. A boot with
FM2_SHADER_KEYS=1 looks up the variants of every pipeline in pipelines.manifest and the pipeline seed. A key with
no .dxbc takes its bytecode from the current output file (the old seed) when that has it; one in neither (never
compiled) is left out. The key hashes the translated HLSL, so regenerate this after a translator change:
a stale entry just never matches, and that shader compiles as it did without the seed.
"""
import os
import re
import sys

# From players' logs: the shaders 10 or more installs compiled during play (after the boot precompile).
# A line is "vs <hash>" or "ps <hash>".
HASHES_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "shader_seed_hashes.txt")


PART_BYTES = 40 * 1024 * 1024


def PartFiles(out):
    """The part files of a seed header (shader_seed_part1.h, ...) that exist now."""
    base, folder = os.path.splitext(os.path.basename(out))[0], os.path.dirname(out) or "."
    found = [f for f in os.listdir(folder) if re.fullmatch(re.escape(base) + r"_part\d+\.h", f)]
    return [os.path.join(folder, f) for f in sorted(found, key=lambda f: int(re.search(r"(\d+)\.h$", f).group(1)))]


def main(argv):
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "gpu", "shader_seed.h")
    args = argv[1:]
    if "--out" in args:
        i = args.index("--out")
        out = args[i + 1]
        del args[i:i + 2]
    variants = "--variants" in args
    if variants:
        args.remove("--variants")
    partial = "--partial" in args
    if partial:
        args.remove("--partial")
    log, cache = args
    # "vs <hash>" or "ps <hash>" per line (a bare hash is a vertex shader, as the first lists were).
    wanted = set()
    for line in open(HASHES_FILE):
        f = line.split()
        if f:
            wanted.add((f[0], f[1]) if f[0] in ("vs", "ps") else ("vs", f[0]))
    keys, variantKeys = {}, set()
    for line in open(log, encoding="latin1"):
        m = re.search(r"shader key: (vs|ps) ([0-9a-f]{16}) ([0-9a-f]{16})", line)
        if m and (m.group(1), m.group(2)) in wanted:
            keys[(m.group(1), m.group(2))] = m.group(3)
        m = re.search(r"shader key: ps(?:k [0-9a-f]{16}|f [0-9a-f]{16} [0-9a-f]+) ([0-9a-f]{16})", line)
        if m and variants:
            variantKeys.add(m.group(1))
    missing = sorted(wanted - set(keys))
    if missing:
        print("not drawn in that log (%d): %s" % (len(missing), " ".join(k + ":" + h for k, h in missing)))
        if not partial:
            return 1
        print("--partial: those are left out")
    # The old seed's bytecode, for keys this cache lacks (a cleared or fresh cache).
    oldSeed = {}
    if os.path.exists(out):
        text = "".join(open(f, encoding="latin1").read() for f in [out] + PartFiles(out))
        for m in re.finditer(r"inline const uint32_t kSeedShader_([0-9a-f]{16})\[\] = \{(.*?)\};", text, re.S):
            oldSeed[m.group(1)] = m.group(2)
    def bytecode(key):
        path = os.path.join(cache, key + ".dxbc")
        if os.path.exists(path):
            return open(path, "rb").read()
        if key in oldSeed:
            return b"".join(int(w, 16).to_bytes(4, "little") for w in re.findall(r"0x[0-9A-Fa-f]+", oldSeed[key]))
        return None
    uncompiled = sorted(k for k in variantKeys if not os.path.exists(os.path.join(cache, k + ".dxbc")) and k not in oldSeed)
    fromOld = sum(1 for k in variantKeys if k in oldSeed and not os.path.exists(os.path.join(cache, k + ".dxbc")))
    if fromOld:
        print("variants taken from the old seed (no .dxbc): %d" % fromOld)
    if uncompiled:
        print("variants without bytecode, left out (%d): %s" % (len(uncompiled), " ".join(uncompiled[:20])))
    variantKeys -= set(uncompiled) | set(keys.values())
    title = "%d compiled vertex and pixel shaders" % len(set(keys.values()))
    if variants:
        title += " and %d pixel shader variants" % len(variantKeys)
    lines = ["// Generated by tools/shader_seed.py: %s." % title,
             "#pragma once", "#include <cstdint>", "",
             "struct SeedShader", "{", "    uint64_t key;", "    uint32_t dwords;", "    const uint32_t* code;", "};", ""]
    entries, total = [], 0
    # Bytecode goes into part files of about PART_BYTES each: GitHub refuses files over 100 MB.
    parts, part, partSize = [], [], 0
    for key in sorted(set(keys.values()) | variantKeys):
        data = bytecode(key)
        if data is None:
            print("%s.dxbc is missing" % key)
            return 1
        if len(data) % 4 or data[:4] != b"DXBC":
            print("%s.dxbc is not bytecode" % key)
            return 1
        total += len(data)
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        block = ["inline const uint32_t kSeedShader_%s[] = {" % key]
        for i in range(0, len(words), 16):
            block.append(",".join("0x%X" % w for w in words[i:i + 16]) + ",")
        block.append("};")
        size = sum(len(l) + 1 for l in block)
        if part and partSize + size > PART_BYTES:
            parts.append(part)
            part, partSize = [], 0
        part += block
        partSize += size
        entries.append("    { 0x%sull, %d, kSeedShader_%s }," % (key.upper(), len(words), key))
    if part:
        parts.append(part)
    for old in PartFiles(out):
        os.remove(old)
    base = os.path.splitext(os.path.basename(out))[0]
    for n, body in enumerate(parts, 1):
        name = "%s_part%d.h" % (base, n)
        head = ["// Generated by tools/shader_seed.py: bytecode for %s (part %d of %d)." % (os.path.basename(out), n, len(parts)),
                "#pragma once", "#include <cstdint>", ""]
        open(os.path.join(os.path.dirname(out) or ".", name), "w", newline="\n").write("\n".join(head + body) + "\n")
        lines.append('#include "%s"' % name)
    lines += ["", "inline const SeedShader kSeedShaders[] = {"] + entries + ["};"]
    open(out, "w", newline="\n").write("\n".join(lines) + "\n")
    print("%d shaders, %d KB of bytecode -> %s" % (len(entries), total // 1024, out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
