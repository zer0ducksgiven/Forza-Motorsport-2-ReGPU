"""Builds src/gpu/shader_seed.h: compiled vertex shaders the game makes at run time, which the first boot's scan
of the game files can't find and nearly every player then compiles during play (up to 28 s each).

  shader_seed.py <game log> <shader cache folder> [--out src/gpu/shader_seed.h]

The log is a run with FM2_SHADER_KEYS=1 that drew them ("shader key: vs <hash> <cache key>"). The bytecode is
<cache key>.dxbc in the cache. The key hashes the translated HLSL, so regenerate this after a translator change:
a stale entry just never matches, and that shader compiles as it did without the seed.
"""
import os
import re
import sys

# From players' logs, 4-5 Nov 2026: the vertex shaders 10 or more installs compiled slowly after boot.
HASHES_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "shader_seed_hashes.txt")


def main(argv):
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "gpu", "shader_seed.h")
    args = argv[1:]
    if "--out" in args:
        i = args.index("--out")
        out = args[i + 1]
        del args[i:i + 2]
    log, cache = args
    wanted = {line.split()[0] for line in open(HASHES_FILE) if line.strip()}
    keys = {}
    for line in open(log, encoding="latin1"):
        m = re.search(r"shader key: vs ([0-9a-f]{16}) ([0-9a-f]{16})", line)
        if m and m.group(1) in wanted:
            keys[m.group(1)] = m.group(2)
    missing = sorted(wanted - set(keys))
    if missing:
        print("not drawn in that log (%d): %s" % (len(missing), " ".join(missing)))
        return 1
    lines = ["// Generated by tools/shader_seed.py: %d compiled vertex shaders." % len(keys),
             "#pragma once", "#include <cstdint>", "",
             "struct SeedShader", "{", "    uint64_t key;", "    uint32_t dwords;", "    const uint32_t* code;", "};", ""]
    entries, total = [], 0
    for key in sorted(set(keys.values())):
        data = open(os.path.join(cache, key + ".dxbc"), "rb").read()
        if len(data) % 4 or data[:4] != b"DXBC":
            print("%s.dxbc is not bytecode" % key)
            return 1
        total += len(data)
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        lines.append("inline const uint32_t kSeedShader_%s[] = {" % key)
        for i in range(0, len(words), 16):
            lines.append(",".join("0x%X" % w for w in words[i:i + 16]) + ",")
        lines.append("};")
        entries.append("    { 0x%sull, %d, kSeedShader_%s }," % (key.upper(), len(words), key))
    lines += ["", "inline const SeedShader kSeedShaders[] = {"] + entries + ["};"]
    open(out, "w", newline="\n").write("\n".join(lines) + "\n")
    print("%d shaders, %d KB of bytecode -> %s" % (len(entries), total // 1024, out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
