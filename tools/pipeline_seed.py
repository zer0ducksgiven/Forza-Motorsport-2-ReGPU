"""Builds src/gpu/pipeline_seed.h: every pipeline in the given pipelines.manifest files (ours, and the
ones players' log uploads carry), merged. The first boot builds those whose shaders the game data
holds, so a first race on a track doesn't stop to build them (report #10).

  pipeline_seed.py <manifest or folder of manifests>... [--out src/gpu/pipeline_seed.h]

A manifest line is "P vs ps blend depth stencilMaskMode flags" (hex), as renderer.cpp writes it.
Only hashes and render state: no game data.
"""
import os
import sys


def manifests(paths):
    for p in paths:
        if os.path.isdir(p):
            for root, _, names in os.walk(p):
                for n in sorted(names):
                    if n.endswith(".manifest"):
                        yield os.path.join(root, n)
        else:
            yield p


def main(argv):
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "gpu", "pipeline_seed.h")
    args = argv[1:]
    if "--out" in args:
        i = args.index("--out")
        out = args[i + 1]
        del args[i:i + 2]
    keys, files = set(), 0
    for path in manifests(args):
        files += 1
        for line in open(path, encoding="ascii", errors="ignore"):
            f = line.split()
            if len(f) == 7 and f[0] == "P":
                try:
                    keys.add(tuple(int(v, 16) for v in f[1:]))
                except ValueError:
                    pass
    lines = ["// Generated by tools/pipeline_seed.py from %d pipelines.manifest files: %d pipelines." % (files, len(keys)),
             "#pragma once", "#include <cstdint>", "",
             "struct SeedPipeline", "{", "    uint64_t vs, ps;", "    uint32_t blend, depth, stencilMaskMode, flags;", "};", "",
             "inline const SeedPipeline kSeedPipelines[] = {"]
    for k in sorted(keys):
        lines.append("    { 0x%016Xull, 0x%016Xull, 0x%X, 0x%X, 0x%X, 0x%X }," % k)
    lines.append("};")
    open(out, "w", newline="\n").write("\n".join(lines) + "\n")
    print("%d manifests, %d pipelines -> %s" % (files, len(keys), out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
