"""Builds src/pipeline_seed.h: every pipeline in the given pipelines.manifest files (ours, and the
ones players' log uploads carry), merged. The first boot builds them all (Host::pipelineSeed), so a first
race on a track doesn't stop to build each.

  pipeline_seed.py <manifest or folder of manifests>... [--out src/pipeline_seed.h]

A manifest line is "P vs ps blend depth stencilMaskMode flags [biasScale biasOffset]" (hex), as ReGPU's
renderer.cpp writes it. Only hashes and render state: no game data. Polygon offsets are rounded as ReGPU
keys them (RoundedBias), which folds many copies of one pass into a few.
"""
import os
import sys


def manifests(paths):
    for p in paths:
        if os.path.isdir(p):
            for root, _, names in os.walk(p):
                for n in sorted(names):
                    if n.endswith(".manifest"):
                        yield os.path.join(root, n)
        else:
            yield p


def rounded_bias(bits):
    # renderer.cpp RoundedBias: 4 mantissa bits, NaN/infinity kept
    return bits if (bits & 0x7F800000) == 0x7F800000 else ((bits + (1 << 18)) & ~((1 << 19) - 1)) & 0xFFFFFFFF


def main(argv):
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "pipeline_seed.h")
    args = argv[1:]
    if "--out" in args:
        i = args.index("--out")
        out = args[i + 1]
        del args[i:i + 2]
    keys, files = set(), 0
    for path in manifests(args):
        files += 1
        for line in open(path, encoding="ascii", errors="ignore"):
            f = line.split()
            if f[:1] != ["P"] or len(f) not in (7, 9):
                continue
            try:
                k = [int(v, 16) for v in f[1:]] + [0, 0][:9 - len(f)]
            except ValueError:
                continue
            k[7] = rounded_bias(k[7])
            keys.add(tuple(k))
    lines = ["// Generated by tools/pipeline_seed.py from %d pipelines.manifest files: %d pipelines." % (files, len(keys)),
             "#pragma once", "", "// pipelines.manifest lines (Host::pipelineSeed).", "inline const char kPipelineSeed[] ="]
    for k in sorted(keys):
        lines.append('    "P %x %x %x %x %x %x %x %x\\n"' % k)
    lines[-1] += ";"
    open(out, "w", newline="\n").write("\n".join(lines) + "\n")
    print("%d manifests, %d pipelines -> %s" % (files, len(keys), out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
