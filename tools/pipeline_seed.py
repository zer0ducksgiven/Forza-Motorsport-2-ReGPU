"""Builds src/gpu/pipeline_seed.h: every pipeline in the given pipelines.manifest files (ours, and the
ones players' log uploads carry), merged. The first boot builds those whose shaders the game data
holds, so a first race on a track doesn't stop to build them (report #10).

  pipeline_seed.py <manifest, folder of manifests, or a previous pipeline_seed.h>... [--out src/gpu/pipeline_seed.h]

A manifest line is "P vs ps blend depth stencilMaskMode flags [fetchMask]" (hex), as renderer.cpp writes it;
the 7th field only when the pipeline draws with a plain-fetch variant (FM2_FETCH_VARIANTS).
Pass the current src/gpu/pipeline_seed.h too when refreshing, or its entries from older uploads drop out:
  py tools/pipeline_seed.py src/gpu/pipeline_seed.h data/manifests <player manifests>
Only hashes and render state: no game data.
"""
import os
import re
import sys

SEED_LINE = re.compile(r"\{ 0x([0-9A-Fa-f]+)ull, 0x([0-9A-Fa-f]+)ull, 0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)(?:, 0x([0-9A-Fa-f]+))? \},")
SEED_FROM = re.compile(r"from (\d+) pipelines\.manifest files")


def manifests(paths):
    for p in paths:
        if os.path.isdir(p):
            for root, _, names in os.walk(p):
                for n in sorted(names):
                    if n.endswith(".manifest"):
                        yield os.path.join(root, n)
        else:
            yield p


def main(argv):
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "gpu", "pipeline_seed.h")
    args = argv[1:]
    if "--out" in args:
        i = args.index("--out")
        out = args[i + 1]
        del args[i:i + 2]
    keys, files = set(), 0
    for path in manifests(args):
        text = open(path, encoding="ascii", errors="ignore").read()
        if path.endswith(".h"):
            # A previous seed: its entries, and the count of manifests it was made from.
            m = SEED_FROM.search(text)
            files += int(m.group(1)) if m else 1
            for m in SEED_LINE.finditer(text):
                keys.add(tuple(int(v, 16) for v in m.groups(default="0")))
            continue
        files += 1
        for line in text.splitlines():
            f = line.split()
            if len(f) in (7, 8) and f[0] == "P":
                try:
                    k = [int(v, 16) for v in f[1:]]
                except ValueError:
                    continue
                keys.add(tuple(k + [0] * (7 - len(k))))
    lines = ["// Generated by tools/pipeline_seed.py from %d pipelines.manifest files: %d pipelines." % (files, len(keys)),
             "#pragma once", "#include <cstdint>", "",
             "struct SeedPipeline", "{", "    uint64_t vs, ps;", "    uint32_t blend, depth, stencilMaskMode, flags;",
             "    uint32_t fetchMask = 0; // the plain-fetch variant's slots (FM2_FETCH_VARIANTS)", "};", "",
             "inline const SeedPipeline kSeedPipelines[] = {"]
    for k in sorted(keys):
        if k[6]:
            lines.append("    { 0x%016Xull, 0x%016Xull, 0x%X, 0x%X, 0x%X, 0x%X, 0x%X }," % k)
        else:
            lines.append("    { 0x%016Xull, 0x%016Xull, 0x%X, 0x%X, 0x%X, 0x%X }," % k[:6])
    lines.append("};")
    open(out, "w", newline="\n").write("\n".join(lines) + "\n")
    print("%d manifests, %d pipelines -> %s" % (files, len(keys), out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
