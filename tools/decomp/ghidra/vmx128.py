"""The Xbox 360's VMX128 instructions, from XenonRecomp's disassembler table (thirdparty/XenonRecomp/thirdparty/
disasm/ppc-dis.c): opcode values and masks, and operands.

  vmx128.py count            how many FM2 functions use them (out/tu4/image.bin, out/decomp/symbols.txt)
  vmx128.py sleigh <out>     a SLEIGH include (.sinc) defining them for Ghidra, for ppc_xenon.slaspec

VMX128 has 128 vector registers, so register numbers are split over several fields (the extract_* functions in
ppc-dis.c). Ghidra can't attach a split field to a register list, so each operand is a subconstructor that
computes the register's offset and exports it. Arithmetic is left as named pcode operations (vaddfp128(a, b)):
enough for the decompiler to follow data through them; loads and stores get their real memory semantics.
"""
import collections
import re
import struct
import sys

DIS = 'thirdparty/XenonRecomp/thirdparty/disasm/ppc-dis.c'

FORMS = {  # name: (value bits from xop, mask bits) from the VX128* macros
    'VX128': (0x3d0, 0x3d0), 'VX128_1': (0x7f3, 0x7f3), 'VX128_2': (0x210, 0x210), 'VX128_3': (0x7f0, 0x7f0),
    'VX128_P': (0x630, 0x630), 'VX128_4': (0x730, 0x730), 'VX128_5': (0x10, 0x10),
}


def table():
    src = open(DIS, errors='replace').read()
    out = []
    for m in re.finditer(r'\{\s*"([\w.]+)",\s*(VX128\w*)\((\d+),\s*(\d+)\),\s*(VX128\w*_MASK)\s*(?:\|\s*([^,]+))?,\s*PPCVEC128,\s*\{([^}]*)\}', src):
        name, form, op, xop, _, extra_mask, ops = m.groups()
        keep, maskbits = FORMS[form]
        value = (int(op) << 26) | (int(xop) & keep)
        mask = (0x3f << 26) | maskbits
        if extra_mask:  # e.g. "| (1 << 5)": fixed bits beyond the form's mask (rare)
            try:
                mask |= eval(extra_mask.replace('UL', ''))
            except Exception:
                pass
        operands = [o.strip() for o in ops.split(',') if o.strip()]
        out.append((name, value, mask, operands))
    return out


def count():
    t = table()
    img = open('out/tu4/image.bin', 'rb').read()
    starts = []
    for line in open('out/decomp/symbols.txt'):
        f = line.split()
        starts.append((int(f[0], 16), int(f[1]), f[-1]))
    used = collections.Counter()
    funcs = 0
    for a, size, name in starts:
        hit = False
        for w in struct.unpack_from('>%dI' % (size // 4), img, a - 0x82000000):
            if (w >> 26) not in (4, 5, 6):
                continue
            for n, v, m, _ in t:
                if w & m == v:
                    used[n] += 1
                    hit = True
                    break
        funcs += hit
    print(f'{len(t)} VMX128 instructions in the table; {funcs} of {len(starts)} functions use them, '
          f'{sum(used.values())} instructions in all')
    print(', '.join('%s %d' % kv for kv in used.most_common(25)))


def _bank(g):
    """The 32 registers of bank g: v0-v31 are the AltiVec registers vs32-vs63, the rest the new v32-v127."""
    return ' '.join(('vs%d' % (32 + i)) if g == 0 else ('v%d' % (g * 32 + i)) for i in range(32))


# Each split register field: the 5-bit low part is defined once per bank (x_d5_0..3, all the same bits) and
# attached to that bank's registers; the subtable picks the bank from the high bits.
BANK_FIELDS = '\n'.join('  x_%s5_%d=(%d,%d)' % (n, g, lo, lo + 4) for n, lo in (('d', 21), ('a', 16), ('b', 11)) for g in range(4))
BANK_ATTACH = '\n'.join('attach variables [ %s ] [ %s ];' % (' '.join('x_%s5_%d' % (n, g) for n in 'dab'), _bank(g)) for g in range(4))
# the attaches come first: a subtable built on a field before its attach exports a bare number (size 0)
BANKS = BANK_ATTACH + '\nattach variables [ x_c3 ] [ %s ];\n' % ' '.join('vs%d' % (32 + i) for i in range(8)) + '\n'.join(
    ['vD128: x_d5_%d is x_d2=%d & x_d5_%d { export x_d5_%d; }' % (g, g, g, g) for g in range(4)] +
    ['vA128: x_a5_%d is x_a1=%d & x_a1h=%d & x_a5_%d { export x_a5_%d; }' % (g, g & 1, g >> 1, g, g) for g in range(4)] +
    ['vB128: x_b5_%d is x_b2=%d & x_b5_%d { export x_b5_%d; }' % (g, g, g, g) for g in range(4)] +
    ['vC128: x_c3 is x_c3 { export x_c3; }']) + '\n'

HEADER = r'''# VMX128, the Xbox 360's vector extension: generated by tools/decomp/ghidra/vmx128.py from XenonRecomp's
# disassembler table. Do not edit; regenerate.
#
# v0-v31 are the AltiVec registers (vs32-vs63 at 0x4200); v32-v127 are new, at 0x11000.

define register offset=0x11000 size=16 [
''' + '\n'.join('  ' + ' '.join('v%d' % (32 + r * 8 + c) for c in range(8)) for r in range(12)) + r'''
];

#@fields (spliced into ppc_common's "define token instr(32)" by install_xenon.py: SLEIGH can't mix tokens)
  x_op=(26,31)
''' + BANK_FIELDS + r'''
  x_d2=(2,3)
  x_a1=(5,5) x_a1h=(10,10)
  x_b2=(0,1)
  x_c3=(6,8)
  x_simm=(16,20) signed
  x_uimm=(16,20)
  x_shb=(6,9)
  x_d3d0=(18,24) x_d3d1=(16,17) x_d3d2=(6,7)
  x_perm_lo=(16,20) x_perm_hi=(6,8)
  x_rc=(6,6)
#@end

# 128-register operands: the high bits pick a bank of 32 (v0-v31 are vs32-vs63), the low 5 bits index into it
''' + BANKS + r'''
vpermimm128: imm is x_perm_lo & x_perm_hi [ imm = x_perm_lo | (x_perm_hi << 5); ] { export *[const]:1 imm; }

EA128: (RA_OR_ZERO, B) is RA_OR_ZERO & B { ea:$(REGISTER_SIZE) = RA_OR_ZERO + B; export ea; }
'''

OPERAND = {  # table operand -> (SLEIGH pattern part, display, value)
    'VD128': ('vD128', 'vD128', 'vD128'), 'VS128': ('vD128', 'vD128', 'vD128'),
    'VA128': ('vA128', 'vA128', 'vA128'), 'VB128': ('vB128', 'vB128', 'vB128'), 'VC128': ('vC128', 'vC128', 'vC128'),
    'VPERM128': ('vpermimm128', 'vpermimm128', 'vpermimm128'),
    'SIMM': ('x_simm', 'x_simm', 'x_simm:1'), 'UIMM': ('x_uimm', 'x_uimm', 'x_uimm:1'), 'SHB': ('x_shb', 'x_shb', 'x_shb:1'),
    'VD3D0': ('x_d3d0', 'x_d3d0', 'x_d3d0:1'), 'VD3D1': ('x_d3d1', 'x_d3d1', 'x_d3d1:1'), 'VD3D2': ('x_d3d2', 'x_d3d2', 'x_d3d2:1'),
}
LOADS = {'lvx128', 'lvxl128'}
STORES = {'stvx128', 'stvxl128'}


def sleigh(out):
    t = table()
    seen = set()
    lines = [HEADER]
    ops = set()
    for name, value, mask, operands in t:
        if (value, mask) in seen:
            continue
        seen.add((value, mask))
        op = re.sub(r'\W', '_', name).rstrip('_') + ('_rc' if name.endswith('.') else '')
        # fixed bits: every masked bit beyond the opcode, written as constraints on 1-bit chunks would be long;
        # instead constrain the whole word through the pattern's x_* fields that the mask fully covers
        cons = ['x_op=%d' % (value >> 26)]
        free = mask & 0x03FFFFFF
        fixed = []
        for bit in range(26):
            if free >> bit & 1:
                fixed.append(bit)
        # group consecutive fixed bits into ad-hoc fields named f<lo>_<hi> (defined below)
        groups = []
        for bit in fixed:
            if groups and groups[-1][1] == bit - 1:
                groups[-1][1] = bit
            else:
                groups.append([bit, bit])
        for lo, hi in groups:
            cons.append('f%d_%d=%d' % (lo, hi, (value >> lo) & ((1 << (hi - lo + 1)) - 1)))
            FIELDS.add((lo, hi))
        mem = 'EA128' if 'RA' in operands or 'RA0' in operands else None
        vals = []
        disp = []
        pat = list(cons)
        for o in operands:
            if o in ('RA', 'RA0', 'RB'):
                if o == 'RB':
                    continue
                pat.append('EA128')
                disp.append('EA128')
                continue
            p, d, v = OPERAND[o]
            if p not in pat:
                pat.append(p)
            if d not in disp:  # SLEIGH shows an operand once (vmaddfp128's accumulator is also its destination)
                disp.append(d)
            vals.append(v)
        dest = operands[0] in ('VD128',) and name not in STORES and not name.startswith('stv')
        if name in LOADS:
            body = 'vD128 = *:16 (EA128 & ~0xf);'
        elif name in STORES:
            body = '*:16 (EA128 & ~0xf) = vD128;'
        else:
            args = list(vals[1:] if dest else vals)
            if mem:
                args = ['EA128'] + [a for a in args if a != 'EA128']
            # accumulating forms read their destination too
            if name.startswith(('vmaddfp128', 'vnmsubfp128', 'vrlimi128', 'vmaddcfp128')) and 'vD128' not in args:
                args = ['vD128'] + args
            ops.add(op)
            call = '%s(%s)' % (op, ', '.join(args))
            body = ('vD128 = %s;' % call) if dest else ('%s;' % call)
        lines.append(':%s %s is %s { %s }' % (name, ', '.join(disp), ' & '.join(pat), body))
    # the Cell unaligned loads and stores the 360 also has (X-form, the normal 32 registers): in the table as CELL
    # (the "l" forms, lvlxl and co, share encodings with newer ISA instructions Ghidra has, and FM2 doesn't use them)
    for name, xop, store in (('lvlx', 519, 0), ('lvrx', 551, 0), ('stvlx', 647, 1), ('stvrx', 679, 1)):
        ops.add(name)
        if store:
            lines.append(':%s vrS,RA_OR_ZERO,B is OP=31 & vrS & RA_OR_ZERO & B & XOP_1_10=%d & Rc=0 '
                         '{ %s(RA_OR_ZERO + B, vrS); }' % (name, xop, name))
        else:
            lines.append(':%s vrD,RA_OR_ZERO,B is OP=31 & vrD & RA_OR_ZERO & B & XOP_1_10=%d & Rc=0 '
                         '{ vrD = %s(RA_OR_ZERO + B); }' % (name, xop, name))
    fields = '\n'.join('  f%d_%d=(%d,%d)' % (lo, hi, lo, hi) for lo, hi in sorted(FIELDS))
    text = '\n'.join(lines)
    text = text.replace('  x_rc=(6,6)\n#@end', '  x_rc=(6,6)\n' + fields + '\n#@end')
    text = text.replace('EA128: (RA_OR_ZERO', '\n'.join('define pcodeop %s;' % o for o in sorted(ops)) + '\n\nEA128: (RA_OR_ZERO')
    open(out, 'w', newline='\n').write(text + '\n')
    print(f'{len(seen)} instructions -> {out}')


def check(dump):
    """Compares Ghidra's decoding (DumpVectorFm2.java's listing) with this table's: the mnemonic, and each 128-register
    operand's number from ppc-dis.c's extract functions (Ghidra shows v0-v31 as vs32-vs63)."""
    extract = {
        'VD128': lambda w: ((w << 3) & 0x60) | ((w >> 21) & 0x1f), 'VS128': lambda w: ((w << 3) & 0x60) | ((w >> 21) & 0x1f),
        'VA128': lambda w: ((w >> 4) & 0x40) | (w & 0x20) | ((w >> 16) & 0x1f),
        'VB128': lambda w: ((w << 5) & 0x60) | ((w >> 11) & 0x1f), 'VC128': lambda w: (w >> 6) & 7,
    }
    t = table()
    good = bad = other = 0
    wrong = collections.Counter()
    examples = {}
    for line in open(dump):
        addr, word, text = line.rstrip('\n').split('\t')
        w = int(word, 16)
        hit = next(((n, ops) for n, v, m, ops in t if w & m == v), None)
        if hit is None:
            other += 1
            continue
        name, ops = hit
        want = []
        for i, o in enumerate(ops):
            if o in extract and not (o in ('VD128', 'VS128') and i > 0):  # an accumulator shown once, as the destination
                r = extract[o](w)
                want.append('vs%d' % (32 + r) if r < 32 else 'v%d' % r)
        mnem = text.split(' ')[0]
        regs = re.findall(r'\bv[s]?\d+\b', text)
        if mnem == name and regs == want:
            good += 1
        else:
            bad += 1
            wrong[name] += 1
            examples.setdefault(name, (addr, word, text, name, want))
    print(f'{good} VMX128 instructions decode as XenonRecomp does, {bad} differ, {other} other vector instructions')
    for n, c in wrong.most_common(20):
        print(' ', n, c, examples[n])


FIELDS = set()

if __name__ == '__main__':
    if sys.argv[1] == 'count':
        count()
    elif sys.argv[1] == 'sleigh':
        sleigh(sys.argv[2])
    elif sys.argv[1] == 'check':
        check(sys.argv[2])
