"""Generates native replacements for the game's HashedName start-up constants (build step for FM2_TITLE_UPDATE).

  py -3 -I tools/decomp/gen_hashed_names.py <out/tu4/image.bin> <out/ppc_tu4/ppc_func_mapping.cpp> <output.cpp>

About 15,800 of the static initialisers the game runs at start-up do one thing: hash a name string with
HashedName's constructor and store the 32-bit result in a global (the property names the UI and game look values
up by). Each function's code is read from the TU4 image and walked instruction by instruction; one that is
exactly that (a frame, the constructor on a stack temporary with a constant string, a load of the hash, a store to
a constant address, the destructor) gets a replacement calling HashedNameInit (src/decomp/hashed_names.cpp) with
its string and global. Anything else in the function and it's left to the recompiled code. The output is made
from your own image at build time, so the game's addresses stay out of the repository.
"""
import re
import struct
import sys

IMAGE_BASE = 0x82000000
CTOR = 0x827F42C8  # HashedName::HashedName(this, const char*)
DTOR = 0x82404EC0  # HashedName::~HashedName (does nothing)


def s16(v):
    return v - 0x10000 if v & 0x8000 else v


def kind(regs, r):
    v = regs.get(r)
    return v[0] if v else None


def match(img, addr, end):
    """(string, global) if the function at addr is a HashedName constant initialiser, else None."""
    regs = {}  # register -> ('const', v) | ('stack', offset) | ('name',) | ('hash',)
    string = dest = None
    stack_obj = None
    dtor = False
    pc = addr
    while pc < end:
        w = struct.unpack_from('>I', img, pc - IMAGE_BASE)[0]
        op = w >> 26
        rd, ra = (w >> 21) & 31, (w >> 16) & 31
        imm = w & 0xFFFF
        if w in (0x7D8802A6, 0x7D8803A6, 0x9181FFF8, 0x8181FFF8):  # mflr/mtlr r12, save/restore r12
            pass
        elif w == 0x4E800020:  # blr
            break
        elif op == 37 and rd == 1 and ra == 1 and s16(imm) < 0:  # stwu r1,-n(r1)
            pass
        elif op == 14 and rd == 1 and ra == 1:  # addi r1,r1,n
            pass
        elif op == 15 and ra == 0:  # lis
            regs[rd] = ('const', (imm << 16) & 0xFFFFFFFF)
        elif op == 14:  # addi / li
            if ra == 0:
                regs[rd] = ('const', s16(imm) & 0xFFFFFFFF)
            elif ra == 1:
                regs[rd] = ('stack', s16(imm))
            elif kind(regs, ra) == 'const':
                regs[rd] = ('const', (regs[ra][1] + s16(imm)) & 0xFFFFFFFF)
            else:
                return None
        elif op == 31 and (w >> 1) & 0x3FF == 444 and not w & 1 and rd == (w >> 11) & 31:  # mr ra,rs
            regs[ra] = regs.get(rd)
            if regs[ra] is None:
                del regs[ra]
        elif op == 18 and w & 3 == 1:  # bl
            disp = w & 0x03FFFFFC
            target = (pc + (disp - 0x04000000 if disp & 0x02000000 else disp)) & 0xFFFFFFFF
            if target == CTOR and string is None and kind(regs, 3) == 'stack' and kind(regs, 4) == 'const':
                stack_obj, string = regs[3][1], regs[4][1]
                regs = {3: ('name',)}
            elif target == DTOR and dest is not None and regs.get(3) == ('stack', stack_obj):
                dtor = True
                regs = {}
            else:
                return None
        elif op == 32 and imm == 0 and regs.get(ra) == ('name',):  # lwz rd,0(the constructed name)
            regs[rd] = ('hash',)
        elif op == 36 and regs.get(rd) == ('hash',) and kind(regs, ra) == 'const' and dest is None:  # stw
            dest = (regs[ra][1] + s16(imm)) & 0xFFFFFFFF
        else:
            return None
        pc += 4
    if string is None or dest is None or not dtor:
        return None
    return string, dest


def main(argv):
    if len(argv) != 4:
        print(__doc__)
        return 1
    img = open(argv[1], 'rb').read()
    addrs = sorted(int(a, 16) for a in re.findall(r'\{ 0x([0-9A-F]+), sub_', open(argv[2]).read()))
    found = []
    for addr, end in zip(addrs, addrs[1:] + [addrs[-1] + 0x400]):
        if end - addr > 0x80 or addr - IMAGE_BASE + (end - addr) > len(img):
            continue
        m = match(img, addr, end)
        if m:
            found.append((addr, *m))
    with open(argv[3], 'w') as f:
        f.write('// Generated by tools/decomp/gen_hashed_names.py from the TU4 image: %d HashedName constants.\n' % len(found))
        f.write('#include "decomp/decomp.h"\n\n#if FM2_TITLE_UPDATE\n')
        for addr, string, dest in found:
            f.write('PPC_FUNC_IMPL(__imp__sub_%08X);\nPPC_FUNC(sub_%08X) { HashedNameInit(ctx, base, __imp__sub_%08X, 0x%08X, 0x%08X); }\n'
                    % (addr, addr, addr, string, dest))
        f.write('#endif\n')
    print('hashed names: %d initialisers replaced' % len(found))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
